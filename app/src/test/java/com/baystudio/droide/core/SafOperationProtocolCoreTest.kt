    @Test(timeout = 30_000) fun oldV2DeepUnlinkedRecordRemainsRecoverableWithoutRewriting() {
        val fixture = fixture()
        val path = (1..65).joinToString("/") { "part$it" }
        assertTrue(path.count { it == '/' } + 1 > fixture.limits.treeDepth)
        val operation = fixture.begin(path)
        val actionId = "00000000-0000-0000-0000-000000000002"
        // Old v2 did not impose the subtree depth bound on unlinked effect paths.
        // This literal is independent of the new serializer and uses only old-core APIs.
        val literal = """{"version":2,"operationId":"${operation.id}","actionId":"$actionId","plan":{"kind":"CREATE_DIRECTORY","path":"$path","original":null,"parent":{"uri":"content://fixture/tree/root/document/existing-parent","documentId":"existing-parent","name":"part64","mimeType":"vnd.android.document/directory","parentDocumentId":"existing-grandparent"},"creationActionId":null,"previous":null,"intended":null,"localArtifacts":[],"requestedMimeType":"vnd.android.document/directory","beforeTree":null},"phase":"PREPARED","result":null,"returnedDocument":null,"providerReturn":null}""".toByteArray(Charsets.UTF_8)
        val file = fixture.journal.file(operation, SafOperationJournal.actionName(actionId, SafEffectPhase.PREPARED))
        fixture.storage.writeNew(file, literal)
        val retained = fixture.operationFiles(operation).associate { it.name to it.readBytes() }

        val recovered = fixture.reopen().recover(operation.id)

        val record = recovered.effects.getValue(actionId)
        assertEquals(2, record.version)
        assertEquals(path, record.plan.path)
        assertEquals(SafEffectPhase.PREPARED, record.phase)
        assertFalse(recovered.activeInvocation)
        assertArrayEquals(literal, SafJournalCodec.encode(SafEffectRecord.serializer(), record))
        assertEquals(retained.keys, fixture.operationFiles(operation).map { it.name }.toSet())
        retained.forEach { (name, bytes) -> assertArrayEquals(bytes, fixture.journal.file(operation, name).readBytes()) }
        assertArrayEquals(sentinel, fixture.workspace.resolve("sentinel.bin").readBytes())
        assertEquals(0, fixture.moves)
    }

