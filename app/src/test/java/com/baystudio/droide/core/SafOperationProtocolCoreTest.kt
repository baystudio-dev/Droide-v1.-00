    @Test fun selfConsistentAcknowledgementWithOrphanParentBlocksAdmission() {
        val fixture = fixture()
        val operation = fixture.begin("a")
        val publisher = SafDurableManifestCommit(fixture.journal)
        publisher.plan(operation, mapOf("a" to fingerprint(replacement)))
        assertTrue(publisher.publish(operation).acknowledged)
        val planFile = fixture.journal.file(operation, "manifest-plan.json")
        val originalPlan = SafJournalCodec.decode(SafManifestPlan.serializer(), planFile.readBytes())
        val trustedFile = fixture.journal.file(operation, "trusted.bin")
        val untrusted = SafJournalCodec.encode(SafLegacyTrustedManifest.serializer(),
            SafLegacyTrustedManifest(entries = sortedMapOf("sentinel.bin" to fingerprint(replacement))))
        trustedFile.writeBytes(untrusted)
        val plannedFile = fixture.journal.file(operation, "planned.bin")
        val originalImage = SafJournalCodec.decode(SafManifestImage.serializer(), plannedFile.readBytes())
        val image = originalImage.copy(parentDigest = untrusted.safDigest(), entries = sortedMapOf(
            "a" to fingerprint(replacement), "sentinel.bin" to fingerprint(replacement)))
        val changed = SafJournalCodec.encode(SafManifestImage.serializer(), image)
        plannedFile.writeBytes(changed)
        fixture.manifest.writeBytes(changed)
        val plan = originalPlan.copy(parentDigest = untrusted.safDigest(),
            trusted = originalPlan.trusted.copy(identity = fixture.storage.describe(trustedFile, fixture.limits.manifestBytes)),
            planned = originalPlan.planned.copy(identity = fixture.storage.describe(plannedFile, fixture.limits.manifestBytes)))
        planFile.writeBytes(SafJournalCodec.encode(SafManifestPlan.serializer(), plan))
        val planDigest = planFile.readBytes().safDigest()
        val candidateFile = fixture.journal.file(operation, "manifest-candidate.json")
        val candidate = SafJournalCodec.decode(SafManifestCandidate.serializer(), candidateFile.readBytes()).copy(
            planDigest = planDigest, identity = fixture.storage.describe(fixture.manifest, fixture.limits.manifestBytes))
        candidateFile.writeBytes(SafJournalCodec.encode(SafManifestCandidate.serializer(), candidate))
        val candidateDigest = candidateFile.readBytes().safDigest()
        fixture.journal.file(operation, "manifest-attempt.json").writeBytes(SafJournalCodec.encode(
            SafManifestAttempt.serializer(), SafManifestAttempt(1, operation.id, candidateDigest)))
        fixture.journal.file(operation, "committed.json").writeBytes(SafJournalCodec.encode(SafManifestAcknowledgement.serializer(),
            SafManifestAcknowledgement(1, operation.id, planDigest, candidateDigest, candidate.identity, plan.revision)))
        val retained = fixture.operationFiles(operation).associate { it.name to it.readBytes() }
        val names = fixture.directory.list()!!.toSet()

        assertTrue(runCatching { fixture.begin("b") }.isFailure)

        assertEquals(names, fixture.directory.list()!!.toSet())
        retained.forEach { (name, bytes) -> assertArrayEquals(bytes, fixture.journal.file(operation, name).readBytes()) }
        assertArrayEquals(changed, fixture.manifest.readBytes())
        assertArrayEquals(sentinel, fixture.workspace.resolve("sentinel.bin").readBytes())
        assertEquals(1, fixture.moves)
    }

    @Test fun manifestPublicationAndBarrierRetryCannotReviveRejectedRestoredHandle() {
        listOf(false, true).forEach { retrying ->
            val fixture = fixture()
            var journal = fixture.journal
            var operation = fixture.begin("a")
            SafDurableManifestCommit(journal).plan(operation, mapOf("a" to fingerprint(replacement)))
            if (retrying) {
                fixture.failDirectory = { fixture.moves > 0 && it == fixture.workspace }
                assertTrue(runCatching { SafDurableManifestCommit(journal).publish(operation) }.isFailure)
                fixture.failDirectory = { false }
                journal = fixture.reopen()
                operation = journal.recover(operation.id)
            }
            assertFalse(operation.poisoned)
            val publisher = SafDurableManifestCommit(journal)
            val publishOrRetry = { if (retrying) publisher.retryExactBarrier(operation) else publisher.publish(operation) }
            val retained = fixture.operationFiles(operation).associate { it.name to it.readBytes() }
            val visible = fixture.manifest.readBytes()
            val moves = fixture.moves
            val envelope = journal.file(operation, "operation.json")
            val key = fixture.storage.key(envelope, false)
            envelope.writeBytes(retained.getValue("operation.json") + byteArrayOf(32))

            assertTrue(runCatching { publishOrRetry() }.isFailure)
            assertTrue(operation.poisoned)
            envelope.writeBytes(retained.getValue("operation.json"))
            assertEquals(key, fixture.storage.key(envelope, false))
            assertTrue(runCatching { publishOrRetry() }.isFailure)

            assertEquals(retained.keys, fixture.operationFiles(operation).map { it.name }.toSet())
            retained.forEach { (name, bytes) -> assertArrayEquals(bytes, journal.file(operation, name).readBytes()) }
            assertFalse(journal.file(operation, "committed.json").exists())
            assertArrayEquals(visible, fixture.manifest.readBytes())
            assertArrayEquals(sentinel, fixture.workspace.resolve("sentinel.bin").readBytes())
            assertEquals(moves, fixture.moves)
        }
    }

