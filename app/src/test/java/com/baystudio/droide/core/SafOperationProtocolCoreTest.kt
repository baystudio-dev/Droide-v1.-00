    private fun Fixture.replacementDelete(op: SafOperationJournal.Operation): SafOperationJournal.Action {
        val payload = journal.preserve(op, workspace.resolve("sentinel.bin"))
        val image = SafTreeEvidence(operationId = op.id, treeUri = journal.anchor.treeUri, rootPath = "change",
            rootDocument = document("change"), entries = listOf(SafTreeEvidenceEntry("", document("change"), payload)))
