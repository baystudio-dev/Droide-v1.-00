                assertTrue(runCatching { f.journal.prepare(op, SafEffectPlan(SafEffectKind.DELETE, "change", document("change"), parent(), null, null, null)) }.isFailure)
                assertTrue(op.effects.isEmpty())
                continue
            }
            val deletion = f.replacementDelete(op)
            val create = f.journal.prepare(op, directoryPlan("change").copy(replacementDeleteActionId = deletion.id))
            if (mode == "corrupt") {
                val image = SafJournalCodec.decode(SafTreeEvidence.serializer(), f.journal.file(op, deletion.admittedPlan.beforeTree!!.name).readBytes())
