    private fun Fixture.completeDeletion(action: SafOperationJournal.Action) {
        journal.attempting(action)
        journal.returned(action, SafEffectReturn.COMPLETED, SafProviderReturn(SafProviderReturnShape.BOOLEAN, boolean = true))
        journal.verified(action)
    }

    private fun Fixture.containedActivation(withProvider: Boolean = false): Pair<SafOperationJournal.Operation, SafOperationJournal.Action> {
        val op = beginTree()
        if (withProvider) {
            val creation = journal.prepare(op, creation("created.bin"))
            journal.attempting(creation)
            journal.returned(creation, SafEffectReturn.COMPLETED, rawUri(document("created.bin")))
            journal.verified(creation, document("created.bin"))
        }
        val stage = root.resolve("activation-stage").apply { mkdir(); resolve("sentinel.bin").writeBytes(sentinel) }
        val backup = root.resolve("activation-backup").apply { mkdir() }
        val artifacts = listOf(SafLocalArtifact(SafLocalArtifactKind.LOCAL_ROOT, workspace.absolutePath, journal.anchor.workspaceKey),
            SafLocalArtifact(SafLocalArtifactKind.STAGE, stage.absolutePath, storage.key(stage, true)),
            SafLocalArtifact(SafLocalArtifactKind.BACKUP, backup.absolutePath, storage.key(backup, true)))
        val previous = journal.preserveActivationInventory(op, SafActivationFiles.capture(journal, op, artifacts[0]) {}) {}
        val intended = journal.preserveActivationInventory(op, SafActivationFiles.capture(journal, op, artifacts[1]) {}) {}
        val action = journal.prepare(op, SafEffectPlan(SafEffectKind.LOCAL_ACTIVATION, "", null, null, null, null, null, localArtifacts = artifacts))
        journal.containActivation(action, previous, intended) {}
        return op to action
    }

    private fun fixture(limits: SafJournalLimits = SafJournalLimits()): Fixture = Fixture(limits)
    private fun fingerprint(bytes: ByteArray) = "f:${bytes.safDigest()}"
    private fun rawUri(document: SafOwnedDocument) = SafProviderReturn(SafProviderReturnShape.URI, uri = document.uri)
    private fun thrown() = SafProviderReturn(SafProviderReturnShape.THREW, diagnosticClass = "java.io.IOException")
    private fun parent() = SafOwnedDocument("content://fixture/tree/root/document/root", "root", "root",
        "vnd.android.document/directory", "tree")
    private fun document(name: String) = SafOwnedDocument("content://fixture/tree/root/document/root%2F$name", "root/$name", name,
        "application/octet-stream", "root")
    private fun creation(path: String) = SafEffectPlan(SafEffectKind.CREATE_FILE, path, null, parent(), null, null, null,
        requestedMimeType = "application/octet-stream")
    private fun directoryPlan(path: String, parentId: String? = null) = creation(path).copy(kind = SafEffectKind.CREATE_DIRECTORY,
        parent = if (parentId == null) parent() else null, requestedMimeType = SafOperationJournal.DIRECTORY_MIME, parentCreationActionId = parentId)
    private fun opaqueDocument(path: String, id: String, parentId: String, mime: String) =
        SafOwnedDocument("content://fixture/tree/root/document/$id", id, path.substringAfterLast('/'), mime, parentId)

    private inner class Fixture(val limits: SafJournalLimits) {
        val root = Files.createTempDirectory("saf-operation-core-").toFile().also { roots += it }
        val workspace = root.resolve("workspace").apply { mkdir() }
        val directory = root.resolve("journal")
        val manifest = workspace.resolve(".droide/saf_manifest.json")
        val trace = arrayListOf<String>()
        var failFile: (File) -> Boolean = { false }
        var failDirectory: (File) -> Boolean = { false }
        var failMove = false
        var beforeRead: (File) -> Unit = {}
        var moves = 0
        val reservation = SafJournalReservation(8, 1024 * 1024, 8L * 1024 * 1024, evidenceFiles = 16)
        val storage = SafOperationStorage(
            forceDirectory = { file ->
                trace += "directory:${file.name}"
                if (failDirectory(file)) throw IOException("injected directory force")
                FileChannel.open(file.toPath(), StandardOpenOption.READ, LinkOption.NOFOLLOW_LINKS).use { it.force(true) }
            },
            forceFile = { file ->
                trace += "file:${file.name}"
                if (failFile(file)) throw IOException("injected file force")
                FileChannel.open(file.toPath(), StandardOpenOption.WRITE, LinkOption.NOFOLLOW_LINKS).use { it.force(true) }
            },
            replaceAtomically = { source, destination ->
                trace += "move"
                moves++
                if (failMove) throw IOException("injected atomic move")
                Files.move(source.toPath(), destination.toPath(), StandardCopyOption.ATOMIC_MOVE, StandardCopyOption.REPLACE_EXISTING)
                Unit
            },
            beforeRead = { beforeRead(it) },
        )
        val journal: SafOperationJournal
        init {
            workspace.resolve("sentinel.bin").writeBytes(sentinel)
            manifest.parentFile!!.mkdir()
            manifest.writeBytes(SafJournalCodec.encode(SafLegacyTrustedManifest.serializer(),
                SafLegacyTrustedManifest(entries = sortedMapOf("sentinel.bin" to fingerprint(sentinel)))))
            journal = SafOperationJournal.create(workspace, "content://fixture/tree/root", directory, storage, limits)
        }
        fun begin(path: String, reserve: SafJournalReservation = reservation) = journal.begin(
            SafOperationRequest(SafOperationKind.WRITE, listOf(path)), listOf(path), reserve)
        fun beginTree() = journal.begin(SafOperationRequest(SafOperationKind.REFRESH, emptyList()), listOf(""), reservation)
        fun completeCreation(action: SafOperationJournal.Action, id: String, parentId: String) {
            val returned = opaqueDocument(action.admittedPlan.path, id, parentId, requireNotNull(action.admittedPlan.requestedMimeType))
            journal.attempting(action)
            journal.returned(action, SafEffectReturn.COMPLETED, rawUri(returned))
            journal.verified(action, returned)
        }
        fun reopen() = SafOperationJournal.open(workspace, "content://fixture/tree/root", directory, storage, limits)
        fun image() = SafJournalCodec.decode(SafManifestImage.serializer(), manifest.readBytes())
        fun operationFiles(operation: SafOperationJournal.Operation) = directory.resolve(operation.id).listFiles()!!.toList()
    }
