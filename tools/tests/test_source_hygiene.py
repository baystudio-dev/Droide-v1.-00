import importlib.util
from pathlib import Path
import tempfile
import unittest

spec = importlib.util.spec_from_file_location("hygiene", Path(__file__).parents[1] / "verify_source_hygiene.py")
hygiene = importlib.util.module_from_spec(spec)
spec.loader.exec_module(hygiene)


class SourceHygieneTests(unittest.TestCase):
    def test_milestone_and_generated_text_remain_rejected(self):
        marker = "C" + "P" + "123-internal"
        self.assertEqual([marker], hygiene.residues("draft " + marker))
        self.assertTrue(hygiene.residues("generated by " + "ChatGPT"))

    def test_hashes_library_names_and_python_abi_are_not_history(self):
        checksum = "sha512-abcC" + "P1oswI/vQibS2G=="
        self.assertEqual([], hygiene.residues(checksum + " ngtcp2 secp256r1 cp312-linux_aarch64"))

    def test_wheel_tag_does_not_hide_another_marker_on_same_line(self):
        marker = "c" + "p" + "123-internal"
        self.assertEqual([marker], hygiene.residues("cp312-linux_aarch64 " + marker))

    def test_original_notice_does_not_exempt_first_party_documents(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            license_file = root / "app/src/main/assets/legal/licenses/upstream.txt"
            license_file.parent.mkdir(parents=True)
            text = "c" + "p" + "6Linux copyright"
            license_file.write_text(text)
            (root / "README.md").write_text(text)
            self.assertEqual(["README.md:1: " + "cp" + "6Linux"], hygiene.audit(root))


if __name__ == "__main__":
    unittest.main()
