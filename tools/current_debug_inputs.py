#!/usr/bin/env python3
"""Fail-closed source/composite boundary for UNADMITTED current debug builds.

Context is generated by the clean-build orchestrator; it is integrity linkage,
not authorization for arbitrary source or a replacement for final APK binding.
"""
from current_native_jni_guard import verify_composite_jni
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import tempfile
import time
ROOT = Path(__file__).resolve().parents[1]
# Five child verifiers each have a reviewed 1800-second cap; allow inventory overhead.
COMPOSITE_TIMEOUT_SECONDS = 5 * 1800 + 300
TREES = ('app/src', 'third_party', 'tools', 'gradle')
FILES = ('app/build.gradle.kts',
    'app/proguard-rules.pro',
    'app/gradle.lockfile',
    'build.gradle.kts',
    'settings.gradle.kts',
    'gradle.properties',
    'gradlew',
    'gradlew.bat')

def regular(path: Path) -> bytes:
    path = Path(path).absolute()
    if '..' in path.parts or any((p.is_symlink() for p in (path, *path.parents))):
        raise ValueError('Unsafe linked/traversal input: ' + str(path))
    if not path.is_file():
        raise ValueError('Missing regular input: ' + str(path))
    return path.read_bytes()

def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()

def source_manifest(root: Path) -> dict[str, str]:
    """Freeze explicit compilation trees, local dependencies and build configuration."""
    root = Path(root).absolute()
    result = {}
    for name in FILES:
        p = root / name
        result[name] = sha(regular(p))
    for name in TREES:
        base = root / name
        if base.is_symlink() or not base.is_dir():
            raise ValueError('Missing/linked source tree: ' + name)
        for p in sorted(base.rglob('*')):
            if '__pycache__' in p.parts or p.suffix == '.pyc':
                continue
            if p.is_symlink():
                raise ValueError('Linked source input: ' + str(p))
            if p.is_file():
                result[str(p.relative_to(root))] = sha(regular(p))
    libraries = root / 'app/libs'
    if not libraries.is_dir() or libraries.is_symlink():
        raise ValueError('Missing/linked local dependency tree')
    for p in sorted(libraries.rglob('*')):
        if p.is_symlink():
            raise ValueError('Linked local dependency')
        if p.is_file():
            result[str(p.relative_to(root))] = sha(regular(p))
    return result

def verify(root: Path, composite: Path, context: Path) -> None:
    root = Path(root).absolute()
    composite = Path(composite).absolute()
    if root != ROOT:
        raise ValueError('Executing verifier differs from selected source root')
    verify_composite_jni(root, composite)
    spec = json.loads(regular(context))
    if set(spec) != {'schemaVersion', 'sourceSha256', 'compositeReceiptSha256'} or spec['schemaVersion'] != 1:
        raise ValueError('Unknown current context schema')
    if source_manifest(root) != spec['sourceSha256']:
        raise ValueError('Source/build graph changed')
    receipt = regular(composite / 'receipt.json')
    if sha(receipt) != spec['compositeReceiptSha256']:
        raise ValueError('Composite receipt changed')
    tool = root / 'tools/current_composite_native_v1.py'
    regular(tool)
    command = [
        'python3', '-B', '-E', '-s', str(tool), 'verify',
        '--root', str(root), '--output', str(composite),
    ]
    environment = {'PATH': '/usr/bin:/bin', 'LANG': 'C.UTF-8', 'LC_ALL': 'C.UTF-8', 'TZ': 'UTC'}
    logs = Path(tempfile.mkdtemp(prefix='droide-composite-consumer-'))
    started = time.monotonic()
    try:
        result = subprocess.run(
            command, cwd=root, env=environment, capture_output=True,
            timeout=COMPOSITE_TIMEOUT_SECONDS,
        )
    except subprocess.TimeoutExpired as error:
        (logs / 'consumer.stdout').write_bytes(error.stdout or b'')
        (logs / 'consumer.stderr').write_bytes(error.stderr or b'')
        (logs / 'consumer.command.json').write_text(json.dumps({
            'argv': command, 'timedOut': True, 'timeoutSeconds': COMPOSITE_TIMEOUT_SECONDS,
            'durationSeconds': time.monotonic() - started,
        }, indent=2) + '\n')
        raise ValueError('Composite verification timed out; partial logs: ' + str(logs)) from error
    (logs / 'consumer.stdout').write_bytes(result.stdout)
    (logs / 'consumer.stderr').write_bytes(result.stderr)
    (logs / 'consumer.command.json').write_text(json.dumps({
        'argv': command, 'returnCode': result.returncode,
        'durationSeconds': time.monotonic() - started,
    }, indent=2) + '\n')
    print('Composite consumer evidence: ' + str(logs))
    if result.returncode:
        raise ValueError('Composite verification failed: ' + result.stderr.decode(errors='replace'))
    if source_manifest(root) != spec['sourceSha256'] or regular(composite / 'receipt.json') != receipt:
        raise ValueError('Inputs changed during verification')
    print('CURRENT_DEBUG_INPUTS_OK APK_UNADMITTED')
if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    for n in ('root', 'composite', 'context'):
        p.add_argument('--' + n, required=True, type=Path)
    a = p.parse_args()
    verify(a.root, a.composite, a.context)
