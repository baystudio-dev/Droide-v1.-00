#!/usr/bin/env python3
"""Check release source text without modifying upstream licenses or frozen evidence."""
from pathlib import Path
import hashlib
import re

ROOT = Path(__file__).resolve().parents[1]
HISTORY_NAME = re.compile(r"(^|/)(cp[0-9]|checkpoint|recovery[-_]|continuation|progress_cp)", re.I)
RESIDUE = re.compile(
    r"(?<![A-Za-z0-9_+/])[Cc][Pp][0-9]{1,3}[A-Za-z0-9_-]*"
    r"|recovery-08[a-z0-9_-]*"
    r"|generated by (?:AI|ChatGPT|Claude|Gemini|Copilot)|AI-generated"
)
PYTHON_ABI = re.compile(r"cp[0-9]{2,3}-linux_[a-z0-9_]+\Z")
SEALED = {
    "docs/verification/agent-workflow-2026-10-11/command-lifecycle-proof/receipt.json": "ae4388d67d859bb254b353b656a41dbd36045ef03441e7f5d19900ebfd95dce4",
    "docs/verification/agent-workflow-2026-10-11/command-lifecycle-audit.md": "62709c95ccf9190b68512d89b28876f58cf036e9364b448261989d7a31b28052",
    "docs/verification/agent-workflow-2026-10-11/command-lifecycle-baseline-proof/receipt.json": "01b00bd3496a8f360963f654f42567f66d95f01c23f66c2ea9b5626e8ca67a89",
}


def residues(text):
    return [match.group() for match in RESIDUE.finditer(text)
            if not PYTHON_ABI.fullmatch(match.group())]


def audit(root):
    failures = []
    for path in sorted(root.rglob("*")):
        relative = path.relative_to(root)
        if ".git" in relative.parts or not path.is_file():
            continue
        name = relative.as_posix()
        if HISTORY_NAME.search(name):
            failures.append(f"{name}: internal history artifact filename")
        if path.suffix in {".jar", ".aar", ".so", ".png", ".svg"}:
            continue
        # The scanner's expressions necessarily contain the strings being rejected.
        if name == "tools/verify_source_hygiene.py":
            continue
        # Original notices must retain names such as ngtcp2 and cp6Linux verbatim.
        # Their integrity and catalog coverage have separate mandatory checks.
        if name.startswith("app/src/main/assets/legal/licenses/"):
            continue
        raw = path.read_bytes()
        if hashlib.sha256(raw).hexdigest() == SEALED.get(name):
            continue
        try:
            text = raw.decode("utf-8")
        except UnicodeDecodeError:
            continue
        for number, line in enumerate(text.splitlines(), 1):
            found = residues(line)
            if found:
                failures.append(f"{name}:{number}: {', '.join(found)}")
    return failures


if __name__ == "__main__":
    failures = audit(ROOT)
    if failures:
        raise SystemExit("RELEASE_SOURCE_FAILED: internal history/generation residue\n" + "\n".join(failures))
    print("SOURCE_HYGIENE_OK")
